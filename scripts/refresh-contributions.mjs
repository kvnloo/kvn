#!/usr/bin/env node
// Refresh CONTRIBUTIONS.md: Kevin's upstream open-source contributions, compacted from two
// public, Kevin-owned sources (the same authorization class as TOOLS.md):
//   - Boplog's oss-contributions.json (PR/issue ledger with GitHub-reported statuses)
//   - gh-contrib-archive's upstream-landings.json (commits verified on upstream branches,
//     with the credit type: authored, co-authored, referenced, review-acknowledged)
// A merged PR and a landed commit are different objects: maintainers often consolidate or
// cherry-pick contributor work, so "merged PRs" undercounts what landed. Both are reported.
//
//   node scripts/refresh-contributions.mjs [--oss file] [--landings file]
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const OSS_URL = "https://kvnloo.github.io/boplog/data/oss-contributions.json";
const LANDINGS_URL = "https://raw.githubusercontent.com/kvnloo/gh-contrib-archive/nightly/data/upstream-landings.json";
const args = process.argv.slice(2);
const opt = (name) => { const i = args.indexOf("--" + name); return i >= 0 ? args[i + 1] : null; };

async function load(path, url) {
  if (path) return JSON.parse(readFileSync(path, "utf8"));
  const response = await fetch(url);
  if (!response.ok) throw new Error(url + " HTTP " + response.status);
  return response.json();
}

const GH = /^https:\/\/github\.com\/[\w.-]+\/[\w.-]+\/(pull|issues|commit)\/[\w]+$/;
const clean = (text, max = 140) => String(text || "").replace(/\s+/g, " ").replace(/[<>]/g, "").trim().slice(0, max);
const day = (iso) => String(iso || "").slice(0, 10);

export function render(oss, landings) {
  const upstream = (oss.contributions || []).filter((c) => c.relationship === "canonical_upstream" && GH.test(c.url));
  const byRepo = new Map();
  for (const c of upstream) {
    if (!byRepo.has(c.repo)) byRepo.set(c.repo, []);
    byRepo.get(c.repo).push(c);
  }
  const groupFor = new Map();
  for (const g of oss.selectedGroups || []) for (const repo of g.repositories || []) groupFor.set(repo, g.label);
  const landed = landings?.repositories || {};
  const count = (list, status) => list.filter((c) => c.status === status).length;
  const s = oss.summary || {};
  const lines = [
    "# CONTRIBUTIONS.md",
    "",
    "Kevin's public upstream open-source contributions (account `kvnloo`). Generated by `scripts/refresh-contributions.mjs` from Boplog's contribution ledger (" + day(oss.generatedAt) + ") and gh-contrib-archive's verified upstream landings (" + (landings?.verifiedOn || "n/a") + ").",
    "",
    "## How to read these numbers",
    "",
    "A merged pull request and a landed commit are different things. Maintainers often consolidate, cherry-pick or re-commit contributor work, so GitHub can show a PR as closed-unmerged while its code is on the upstream branch. \"Landed commits\" below are commits verified on the upstream branch by SHA, labeled by credit: authored (Kevin is the commit author), co-authored (Kevin is a credited co-author), referenced (the landing commit credits Kevin's PR), review-acknowledged (credited for review; not code authorship). Coverage is not exhaustive.",
    "Evidence: " + LANDINGS_URL.replace("raw.githubusercontent.com/kvnloo/gh-contrib-archive/nightly", "github.com/kvnloo/gh-contrib-archive/blob/nightly") + " · " + OSS_URL,
    "",
    "## Upstream totals",
    "",
    "Across " + (s.distinctUpstreamCommunities ?? "?") + " upstream communities: " + (s.mergedUpstreamPullRequests ?? "?") + " merged pull requests, " + (s.openReadyUpstreamPullRequests ?? "?") + " open ready-for-review pull requests, " + (s.draftUpstreamPullRequests ?? "?") + " draft pull requests, and " + (s.upstreamIssuesAndProposals ?? "?") + " issues and proposals (Boplog ledger, " + day(oss.generatedAt) + ").",
    "Evidence: https://kvnloo.github.io/boplog/ · " + OSS_URL
  ];
  const communities = (oss.selectedGroups || []).filter((g) => g.contributionCount > 0)
    .sort((a, b) => b.contributionCount - a.contributionCount || a.label.localeCompare(b.label));
  if (communities.length) {
    lines.push("", "## Main upstream communities", "",
      "Open-source projects Kevin contributes to most, by number of pull requests and issues in the Boplog ledger: " +
      communities.map((g) => g.label + " (" + g.repositories.join(", ") + ", " + g.contributionCount + ")").join("; ") + ".",
      "Evidence: https://kvnloo.github.io/boplog/ · " + OSS_URL);
  }

  // Repositories ordered by landed commits, then merged PRs, then total activity.
  const repos = [...new Set([...byRepo.keys(), ...Object.keys(landed)])];
  const score = (repo) => [(landed[repo]?.commits || []).length, count(byRepo.get(repo) || [], "merged"), (byRepo.get(repo) || []).length];
  repos.sort((a, b) => { const x = score(a), y = score(b); return y[0] - x[0] || y[1] - x[1] || y[2] - x[2] || a.localeCompare(b); });

  for (const repo of repos.slice(0, 14)) {
    const list = byRepo.get(repo) || [];
    const commits = landed[repo]?.commits || [];
    const label = groupFor.get(repo);
    lines.push("", "## " + (label ? label + " (" + repo + ")" : repo), "");
    const credit = {};
    for (const c of commits) credit[c.credit] = (credit[c.credit] || 0) + 1;
    if (commits.length) {
      const parts = Object.entries(credit).sort((a, b) => b[1] - a[1]).map(([k, v]) => v + " " + k);
      const code = commits.length - (credit["review-acknowledged"] || 0);
      const plural = (n, word) => n + " " + word + (n === 1 ? "" : "s");
      lines.push("Summary: " + plural(code, "commit") + " with Kevin's code credit " + (code === 1 ? "is" : "are") + " verified on " + repo + "'s " + (landed[repo].upstreamBranch || "upstream") + " branch" + (credit["review-acknowledged"] ? ", plus " + credit["review-acknowledged"] + " that credit his reviews" : "") + " (" + plural(commits.length, "landed commit") + " in total: " + parts.join(", ") + ").");
    }
    lines.push("Pull requests: " + count(list, "merged") + " merged, " + count(list, "open_ready") + " open, " + count(list, "open_draft") + " draft, " + count(list, "closed_unmerged") + " closed without merge. Issues and proposals: " + (count(list, "open") + count(list, "closed")) + ".");
    const examples = commits.filter((c) => c.credit !== "review-acknowledged")
      .sort((a, b) => String(b.at).localeCompare(String(a.at))).slice(0, 8)
      .map((c) => "- " + day(c.at) + " " + clean(c.title) + " (" + c.credit + ") " + c.url);
    const merged = list.filter((c) => c.status === "merged").sort((a, b) => String(b.updatedAt).localeCompare(String(a.updatedAt))).slice(0, examples.length ? 3 : 6)
      .map((c) => "- merged PR: " + clean(c.title) + " " + c.url);
    if (examples.length) lines.push("Recent landed work:", ...examples);
    if (merged.length) lines.push(...(examples.length ? [] : ["Merged pull requests:"]), ...merged);
    lines.push("Evidence: https://github.com/" + repo + "/pulls?q=author%3Akvnloo");
  }
  return lines.join("\n") + "\n";
}

if (import.meta.url === "file://" + process.argv[1]) {
  const oss = await load(opt("oss"), OSS_URL);
  const landings = await load(opt("landings"), LANDINGS_URL);
  const text = render(oss, landings);
  writeFileSync(join(root, "CONTRIBUTIONS.md"), text);
  console.log("Wrote CONTRIBUTIONS.md (" + text.length + " chars)");
}
